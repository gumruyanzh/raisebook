const FOLDED: Record<string, string> = Object.fromEntries(
  Object.entries(LEGACY_ZONES).map(([k, v]) => [k.toLowerCase(), v]),
);

/** `Asia/Calcutta` → `Asia/Kolkata`, `Etc/UTC` or `utc` → `UTC`; other ids unchanged. */
export function canonicalZone(id: string): string {
  const tz = (id ?? "").trim();
  if (!tz) return "UTC";
  if (tz.toUpperCase() === "UTC") return "UTC";
  return LEGACY_ZONES[tz] ?? FOLDED[tz.toLowerCase()] ?? tz;
}
